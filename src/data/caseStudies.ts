export function matchCaseStudy(prompt: string): CaseStudy {
  let best = CASE_STUDIES[0];
  let bestScore = 0;
  for (const cs of CASE_STUDIES) {
    const s = scoreKeys(prompt, cs.keys);
    if (s > bestScore) {
      bestScore = s;
      best = cs;
    }
  }
  // No keyword hits → fall back to Microsoft (Technology), preserving prior
  // behaviour for blank / off-topic prompts.
  return bestScore > 0 ? best : CASE_STUDIES[0];
}

export type MatchedAxis = "industry" | "use-case" | "role";

export function matchSimilarStudies(prompt: string): {
  top: CaseStudy;
  neighbors: Array<{ study: IndexedStudy; matchedAxis: MatchedAxis }>;
  clusterSize: number;
  medianTime: string;
  medianSample: number;
  medianLanguages: number;
  similarityScore: number;
} {
  const top = matchCaseStudy(prompt);
  const facets = matchFacets(prompt);
  const neighbors = rankNeighbors(top, facets, 3);
  const medians = clusterMedians(top.tag);

  // Similarity score: winner's keyword-hit count normalized against the max
  // across all clusters, scaled to a 0.20–0.95 range so even thin matches
  // read as "scored against" rather than "no signal."
  const winnerScore = scoreKeys(prompt, top.keys);
  const allScores = CASE_STUDIES.map((cs) => scoreKeys(prompt, cs.keys));
  const maxAcross = Math.max(...allScores, 1);
  const similarityScore = 0.2 + 0.75 * (winnerScore / maxAcross);

  return {
    top,
    neighbors,
    clusterSize: clusterSizeFor(top.tag) + 1, // +1 to count the top match itself
    medianTime: medians.time,
    medianSample: medians.sample,
    medianLanguages: medians.languages,
    similarityScore,
  };
}
